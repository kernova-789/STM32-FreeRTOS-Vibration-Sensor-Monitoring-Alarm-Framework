#pragma once

#include <stdint.h>

/*
 * STM32F103CB Flash 布局。
 *
 * 应用程序配置页归应用程序所有，本 Bootloader 绝不会擦除或写入这些页面。
 */
#define BOOT_FLASH_PAGE_SIZE UINT32_C(0x00000400)
#define BOOT_APP_START_ADDRESS UINT32_C(0x08005000)
#define BOOT_APP_END_ADDRESS UINT32_C(0x0801F400)
#define BOOT_APP_PAGE_COUNT                                                \
  ((BOOT_APP_END_ADDRESS - BOOT_APP_START_ADDRESS) / BOOT_FLASH_PAGE_SIZE)

#define BOOT_SETTINGS_PAGE0_ADDRESS UINT32_C(0x0801F400)
#define BOOT_SETTINGS_PAGE1_ADDRESS UINT32_C(0x0801F800)
#define BOOT_REQUEST_PAGE_ADDRESS UINT32_C(0x0801FC00)
#define BOOT_REQUEST_FLAG_ADDRESS UINT32_C(0x0801FF30)
#define BOOT_REQUEST_FLAG_VALUE UINT16_C(0x0000)

#define BOOT_SRAM_START_ADDRESS UINT32_C(0x20000000)
#define BOOT_SRAM_END_ADDRESS UINT32_C(0x20005000)

/* 固定的上位机 CAN 协议。 */
#define BOOT_CAN_TX_STANDARD_ID UINT32_C(0x002)
#define BOOT_CAN_IGNORED_SENSOR_ID UINT32_C(0x001)
#define BOOT_CAN_FRAME_SIZE 8U
#define BOOT_CAN_HANDSHAKE_COMMAND UINT8_C(0x06)

#define BOOT_OTA_PACKET_SIZE 264U
#define BOOT_OTA_PACKET_NUMBER_OFFSET 2U
#define BOOT_OTA_PACKET_DATA_OFFSET 6U
#define BOOT_OTA_PACKET_DATA_SIZE 256U
#define BOOT_OTA_PACKET_CHECKSUM_INDEX 263U
#define BOOT_OTA_FINAL_PACKET_NUMBER UINT32_C(0xFFFFFFFF)

#define BOOT_REPLY_COMMAND UINT8_C(0x01)
#define BOOT_REPLY_STATUS UINT8_C(0x0A)

/*
 * 等待新固件包时，每隔 2 秒重发一次确认消息，最多额外重发 2 次；
 * 超过 5 秒仍未收到完整数据包则判定升级失败。
 */
#define BOOT_REPLY_RETRY_INTERVAL_MS UINT32_C(2000)
#define BOOT_REPLY_RETRY_COUNT 2U
#define BOOT_RECEIVE_TIMEOUT_MS UINT32_C(5000)

/* CAN 接收活动指示灯的亮灭节拍。 */
#define BOOT_CAN_ACTIVITY_ON_MS UINT32_C(40)
#define BOOT_CAN_ACTIVITY_OFF_MS UINT32_C(20)
